-- 1. Table des modèles de rôles et permissions par défaut
CREATE TABLE IF NOT EXISTS roles (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  permissions JSONB NOT NULL,
  is_system BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Table des utilisateurs (inscription, validation admin & droits personnalisés)
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  department TEXT NOT NULL DEFAULT 'Parc Auto Protocole',
  role_id TEXT NOT NULL REFERENCES roles(id) ON UPDATE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'suspended')),
  permissions JSONB NOT NULL,
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  validated_at TIMESTAMPTZ,
  validated_by TEXT,
  last_login_at TIMESTAMPTZ
);

-- 3. Table centrale partagée des ordres de réparation
CREATE TABLE IF NOT EXISTS repair_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_date DATE NOT NULL,
  marque TEXT NOT NULL,
  modele TEXT NOT NULL,
  immat TEXT NOT NULL,
  vin TEXT NOT NULL DEFAULT '',
  km INTEGER NOT NULL CHECK (km >= 0),
  checks JSONB NOT NULL,
  remarque TEXT NOT NULL DEFAULT '',
  tech TEXT NOT NULL DEFAULT '',
  ctrl TEXT NOT NULL DEFAULT '',
  custom_values JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by_id TEXT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_by_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  updated_by_name TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Configuration dynamique du formulaire d'enregistrement (colonnes & points de contrôle)
CREATE TABLE IF NOT EXISTS form_config (
  id TEXT PRIMARY KEY,
  config JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by TEXT
);

-- 5. Journal d'activité temps réel (audit des validations, droits et ordres)
CREATE TABLE IF NOT EXISTS activity_logs (
  id UUID PRIMARY KEY,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actor_id TEXT NOT NULL,
  actor_name TEXT NOT NULL,
  action TEXT NOT NULL,
  target_label TEXT NOT NULL,
  details TEXT
);

-- Index d'optimisation pour les filtres, recherches et statistiques
CREATE INDEX IF NOT EXISTS idx_users_status ON users(status);
CREATE INDEX IF NOT EXISTS idx_users_role_id ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_repair_orders_work_date ON repair_orders(work_date DESC);
CREATE INDEX IF NOT EXISTS idx_repair_orders_marque ON repair_orders(marque);
CREATE INDEX IF NOT EXISTS idx_repair_orders_created_by ON repair_orders(created_by_id);
CREATE INDEX IF NOT EXISTS idx_activity_logs_timestamp ON activity_logs(timestamp DESC);
